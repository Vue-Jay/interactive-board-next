/** Understands natural school requests, e.g. "сделай десять простых задач на треугольники". */
export function parseCurriculumRequest(
  input: string,
  selectedSubject = "",
  selectedCount = 5,
  selectedLevel: CurriculumAiLevel = "medium",
  selectedTool: CurriculumAiTool = "assignment",
): ParsedCurriculumRequest {
  const qty = new RegExp(`(^|\\s)(\\d{1,2}|${Object.keys(numberWords).join("|")})(?:\\s+[а-яё-]+){0,2}\\s+(?:${countUnits})`, "iu");
  const countMatch = input.match(qty);
  const requestedCount = countMatch ? (numberWords[countMatch[2].toLocaleLowerCase("ru-RU")] ?? Number(countMatch[2])) : selectedCount;
  const hasCount = Boolean(countMatch);
  const hardRequest = /посложнее|сложнее|нестандартн|(?<!не)сложн(?:ые?|ых)\s+(?:задач|задан|упражнен|тест|пример|вопрос)|сложный уровень|повышенн[а-яё]*\s+сложност[а-яё]*|углубл|олимпиад|продвинут|высокого уровня|поиск ошибк|исследовательск[а-яё]*\s+(?:задач|задан|упражнен)/i.test(input);
  // Advanced reasoning is part of the ordinary generation flow. Detect it from
  // the user's wording instead of exposing a separate "olympiad" mode.
  const olympiadRequest = /олимпиад|нестандартн|задач[а-яё]*\s+на\s+сообразительность|необычн[а-яё]*\s+(?:задач|задан)|(?:исследовательск|логическ|комбинированн|доказательн)[а-яё]*\s+(?:задач|задан|упражнен)|задач[а-яё]*\s+(?:с\s+(?:подвохом|несколькими\s+условиями)|на\s+(?:доказательств\w*|поиск\s+ошибк\w*|исследован\w*|рассужден\w*|несколько\s+способ\w*))|(?:докажи|обоснуй|найди\s+ошибк\w*|сформулируй\s+контрпример)|контрпример[а-яё]*|граничн\w*\s+случа[а-яё]*|несколькими\s+ограничени[а-яё]*/i.test(input);
  const easyRequest = /попроще|полегче|несложн[а-яё]*|прост(?:ые?|ых|ую)\s+(?:задач|задан|упражнен|тест|пример|вопрос|карточ)|простой уровень|базов\w* уровень|начинающ|для новичк|начальн\w* уровень/i.test(input);
  const hasLevel = hardRequest || easyRequest;
  const inferredLevel: CurriculumAiLevel = hardRequest ? "hard" : "easy";
  let topic = countMatch ? input.replace(qty, " ") : input;
  const numericGrade = input.match(/(?:^|\s)(\d{1,2})(?:-(?:й|го|м))?\s*(?:класс[а-яё]*|кл\.?)/i);
  const wordGrade = input.match(new RegExp(`(?:^|\\s)(${Object.keys(gradeWords).sort((a, b) => b.length - a.length).join("|")})\\s+класс[а-яё]*`, "iu"));
  const nounGrade = input.match(new RegExp(`(?:^|\\s)(${Object.keys(gradeNouns).sort((a, b) => b.length - a.length).join("|")})[а-яё]*`, "iu"));
  const grade = numericGrade ? Math.min(11, Math.max(1, Number(numericGrade[1])))
    : wordGrade ? gradeWords[wordGrade[1].toLocaleLowerCase("ru-RU")] ?? null
      : nounGrade ? gradeNouns[nounGrade[1].toLocaleLowerCase("ru-RU")] ?? null : null;
  const gradePhrase = numericGrade?.[0] ?? wordGrade?.[0]?.trim() ?? nounGrade?.[0]?.trim();
  if (gradePhrase) topic = topic.replace(gradePhrase, " ");
  const explicitSubjectPhrases: [string, RegExp][] = [
    ["Математика", /(?:^|\s)по\s+(?:математик[а-яё]*|алгебр[а-яё]*|геометр[а-яё]*)(?=\s|$)/iu],
    ["Физика", /(?:^|\s)по\s+физик[а-яё]*(?=\s|$)/iu],
    ["Химия", /(?:^|\s)по\s+хими[а-яё]*(?=\s|$)/iu],
    ["Биология", /(?:^|\s)по\s+биолог[а-яё]*(?=\s|$)/iu],
    ["География", /(?:^|\s)по\s+географ(?:ия|ии|ию|ией)(?=\s|$)/iu],
    ["Русский язык", /(?:^|\s)по\s+русск[а-яё]*\s+язык[а-яё]*(?=\s|$)/iu],
    ["Литература", /(?:^|\s)по\s+литератур[а-яё]*(?=\s|$)/iu],
    ["История", /(?:^|\s)по\s+истор[а-яё]*(?=\s|$)/iu],
    ["Обществознание", /(?:^|\s)по\s+обществознани[а-яё]*(?=\s|$)/iu],
    ["Информатика", /(?:^|\s)по\s+информатик[а-яё]*(?=\s|$)/iu],
    ["Иностранный язык", /(?:^|\s)(?:по|на)\s+(?:иностранн[а-яё]*\s+язык[а-яё]*|английск[а-яё]*(?:\s+язык[а-яё]*)?|english)(?=\s|$)/iu],
  ];
  let explicitSubject = selectedSubject;
  if (!explicitSubject) {
    for (const [subject, pattern] of explicitSubjectPhrases) {
      if (pattern.test(topic)) {
        explicitSubject = subject;
        topic = topic.replace(pattern, " ");
        break;
      }
    }
  }
  const quotedCanonicalTopic = input.match(/[«“"]([^»”"]+)[»”"]/u)?.[1]?.trim();
  const preserveQuotedCanonicalTopic = Boolean(quotedCanonicalTopic && matchCanonicalCurriculumTopic(quotedCanonicalTopic));
  if (preserveQuotedCanonicalTopic && quotedCanonicalTopic) {
    topic = quotedCanonicalTopic;
    explicitSubject ||= matchCanonicalCurriculumTopic(quotedCanonicalTopic);
  }
  const subjectForCleanup = explicitSubject || detectCurriculumSubject(topic);
  if (!preserveQuotedCanonicalTopic) {
    topic = topic.replace(/[,:;.!?«»“”]+/g, " ");
    for (let pass = 0; pass < 3; pass += 1) {
      topic = topic
        .replace(/^\s*(?:(?:пожалуйста|мне|мне нужно|мне нужна|мне нужны|нужно|нужна|нужны|хочу|можно|создай|составь|подготовь|подготовить|сгенерируй|сделай|дай|придумай|напиши|подбери|сформируй|сгенерировать|реши|решить|вычисли|найди|объясни|изучи|разбери|расскажи|покажи|хотелось бы|давай)\s+)+/i, "")
        .replace(/^\s*(?:(?:что-нибудь|что нибудь|нескольк[а-яё]*|пару|пара|парочк[а-яё]*|много|попроще|полегче|посложнее|сложнее|л[её]гк(?:ую|ие|их|ое)|сложн(?:ую|ые|ых|ое)|углублённ[а-яё]*|олимпиадн[а-яё]*|нестандартн[а-яё]*|необычн[а-яё]*|исследовательск[а-яё]*|комбинированн[а-яё]*|доказательн[а-яё]*|базов[а-яё]*|продвинут[а-яё]*)\s+)+/i, "")
        .replace(/^\s*прост(?:ую|ые|ых|ое)\s+(?=(?:задач|задан|упражнен|тест|пример|карточ))/i, "")
        .replace(/^\s*(?:(?:задач[а-яё]*|задани[а-яё]*|упражнен[а-яё]*|тест[а-яё]*|викторин[а-яё]*|проверочн[а-яё]*|контрольн[а-яё]*|самостоятельн[а-яё]*|флеш[- ]?карточ[а-яё]*|карточ[а-яё]*|вопрос[а-яё]*|пример[а-яё]*|практическ\w*)\s+)+/i, "")
        .replace(/^\s*(?:(?:по теме|на тему|по|на|про|тема|теме|для|о)\s+)+/i, "");
    }
    topic = topic.replace(/^\s*(?:(?:по теме|на тему|по|на|про|тема|теме|для|о)\s+)+/i, "")
      .replace(/\s+(?:для|учени(?:к|ца|кам|кам)?|учащимс[яи])\s*$/i, "")
      .replace(/\s+(?:в|на|по|для|о|об|из|к|ко|с|со|от)\s*$/i, "")
      .replace(/\s+(?:для\s+)?(?:начинающ[а-яё]*|новичк[а-яё]*|посложнее|полегче|попроще)\s*$/i, "")
      .replace(/\s+/g, " ").trim();
  }
  const toolMatch = /карточ[а-яё]*|флеш.?карточ|flash.?card/i.test(input)
    ? "flashcards"
    : /(?:^|\s)(?:тест[а-яё]*|проверочн[а-яё]*|контрольн[а-яё]*|викторин[а-яё]*|quiz|самостоятельн[а-яё]*|вопрос(?:а|ы|ов|ам|ами|ах)?)(?=$|[\s,.:;!?])/i.test(input)
      ? "quiz"
      : /задач|упражнен|пример|домашн|практик|задани|диалог|тем[а-яё]*/i.test(input)
        ? "assignment"
        : null;
  return {
    subject: explicitSubject || detectCurriculumSubject(topic) || (topic ? subjectForCleanup : ""),
    topic,
    count: Math.max(1, Math.min(15, Math.round(Number(requestedCount) || selectedCount || 5))),
    grade,
    tool: toolMatch ?? selectedTool,
    level: hasLevel ? inferredLevel : selectedLevel,
    hasCount,
    hasTool: Boolean(toolMatch),
    hasLevel,
    olympiad: olympiadRequest,
  };
}

export function generateCurriculumAi(tool: CurriculumAiTool, topic: string, level: CurriculumAiLevel, count: number, selectedSubject = ""): CurriculumAiResult {
  const request = parseCurriculumRequest(topic, selectedSubject, count, level, tool);
  const subject = request.subject;
  const clean = request.topic;
  const safeCount = request.count;
  const effectiveLevel = request.level;
  if (!clean) throw new Error("Укажите тему задания.");
  if (!subject) throw new Error("Не удалось определить предмет. Выберите его в списке.");
  const mappedGrade = matchCanonicalCurriculumGrade(clean, subject);
  if (request.grade) {
    const classSpecificGrade = matchCanonicalCurriculumGrade(`${clean} в ${request.grade} классе`, subject);
    if (mappedGrade && !gradeMatchesMappedBand(request.grade, mappedGrade)
      && !gradeMatchesMappedBand(request.grade, classSpecificGrade)) {
      throw new Error(`По предварительной карте Lectrus тема «${clean}» отнесена к ${mappedGrade} классу. В запросе указан ${request.grade} класс. Уточните тему или класс.`);
    }
  }
  if (subject === "Математика") {
    const mathLevel: MathAiLevel = effectiveLevel === "easy" ? "primary" : effectiveLevel === "hard" ? "advanced" : "basic";
    const generationGrade = request.grade ?? (/^\d{1,2}$/.test(mappedGrade) ? Number(mappedGrade) : undefined);
    const math = generateMathAi("auto" as MathAiMode, mathLevel, safeCount, clean, true, generationGrade, request.olympiad);
    const gradeLabel = request.grade ? ` · ${request.grade} класс` : "";
    const gradeInstruction = getGradeTaskInstruction(request.grade, effectiveLevel);
    const addGradeInstruction = (item: string) => gradeInstruction ? `${item}\n${gradeInstruction}` : item;
    if (tool === "assignment") return { title: `${math.detected} · ${clean}${gradeLabel}`, items: math.items.map(addGradeInstruction), answers: math.answers, subject, detected: math.detected };
    if (tool === "quiz") return {
      title: `Проверочная работа · Математика · ${clean}${gradeLabel}`,
      items: math.items.map((q, i) => addGradeInstruction(`${i + 1}. ${q.replace(/\s*=\s*$/, " = ?")}`)),
      answers: math.answers, subject, detected: math.detected,
    };
    return {
      title: `Карточки по математике · ${clean}${gradeLabel}`,
      items: math.items.map((q, i) => `Карточка ${i + 1}\nВопрос: ${q.replace(/\s*=\s*$/, " — чему равно выражение?")}${gradeInstruction ? `\n${gradeInstruction}` : ""}\nОтвет: ${math.answers[i]}`),
      answers: math.answers, subject, detected: math.detected,
    };
  }

  const seenPrompts = new Set<string>();
  let fallbackVariant = 0;
  const exercises = Array.from({ length: safeCount }, (_, i) => {
    let exercise = request.olympiad
      ? generateSubjectChallengeExercise(subject, clean, i)
      : generateSubjectExercise(subject, clean, effectiveLevel, i);
    let normalizedPrompt = exercise.prompt.toLocaleLowerCase("ru-RU").replace(/\s+/g, " ").trim();
    while (seenPrompts.has(normalizedPrompt) && fallbackVariant < 30) {
      exercise = generateSubjectExerciseVariant(subject, clean, fallbackVariant++);
      normalizedPrompt = exercise.prompt.toLocaleLowerCase("ru-RU").replace(/\s+/g, " ").trim();
    }
    seenPrompts.add(normalizedPrompt);
    if (effectiveLevel === "easy") return { ...exercise, prompt: `${exercise.prompt} Работай по шагам; при необходимости пользуйся конспектом.` };
    if (effectiveLevel === "hard" && !request.olympiad) return {
      ...exercise,
      prompt: `${exercise.prompt} Дополнительно объясни выбор способа решения и проверь вывод на другом примере.`,
      answer: `${exercise.answer} В ответе объясни ход рассуждения и проверь вывод на другом примере.`,
    };
    return exercise;
  });
  const answers = exercises.map((exercise, i) => `${i + 1}. ${exercise.answer}`);
  const gradeLabel = request.grade ? ` · ${request.grade} класс` : "";
  const gradeInstruction = getGradeTaskInstruction(request.grade, effectiveLevel);
  const addGradeInstruction = (prompt: string) => gradeInstruction ? `${prompt}\n${gradeInstruction}` : prompt;
  if (tool === "assignment") return {
    title: `Практика · ${subject} · ${clean}${gradeLabel}`,
    items: exercises.map((exercise, i) => `${i + 1}. ${addGradeInstruction(exercise.prompt)}`), answers, subject, detected: subject,
  };
  if (tool === "quiz") return {
    title: `Проверочная работа · ${subject} · ${clean}${gradeLabel}`,
    items: exercises.map((exercise, i) => `${i + 1}. ${addGradeInstruction(exercise.prompt)}`), answers, subject, detected: subject,
  };
  return {
    title: `Карточки · ${subject} · ${clean}${gradeLabel}`,
    items: exercises.map((exercise, i) => `Карточка ${i + 1}\nВопрос: ${addGradeInstruction(exercise.prompt)}\nОтвет: ${exercise.answer}`),
    answers, subject, detected: subject,
  };
}

