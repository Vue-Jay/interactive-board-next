export function detectCurriculumSubject(topic: string, selected = ""): string {
  if (LEKTRUS_SCHOOL_SUBJECTS.includes(selected as typeof LEKTRUS_SCHOOL_SUBJECTS[number])) return selected;
  const genericTopic = topic.toLocaleLowerCase("ru-RU").replace(/ё/g, "е").replace(/[«»“”.,!?]/g, " ").replace(/\s+/g, " ").trim();
  if (/^(?:тема|тему|предмет|материал[а-яё]*|задание|упражнение)(?:\s+(?:простыми словами|подробнее|на сегодня|сегодняшняя))?$/iu.test(genericTopic)
    || /^(?:изученн[а-яё]*|пройденн[а-яё]*|текущ[а-яё]*|сегодняшн[а-яё]*)\s+материал[а-яё]*$/iu.test(genericTopic)) return "";
  if (/сравнительн[а-яё]*\s+степен[а-яё]*\s+прилагател[а-яё]*.*английск[а-яё]*/iu.test(genericTopic)) return "Иностранный язык";
  // These very short labels have common meanings in multiple subjects. Do not
  // let an exact broad catalog alias turn an underspecified request into a guess.
  if (/^(?:кор(?:ень|ня|ню|нем|ни|ней|нями)|предложени(?:е|я|ю|и|ем|ях)|таблиц(?:а|у|е|ы|ой|ам|ами|ах)|состав(?:а|у|ом|е|ы|ов)?|значени[еяю]|признак[а-яё]*|свойств[а-яё]*|част[ьиаяей]|систем[а-яё]*|формул[а-яё]*|преобразован[а-яё]*|строени[а-яё]*|классификаци[а-яё]*|работ[а-яё]*\s+в\s+класс[а-яё]*|заданн[а-яё]*\s+материал[а-яё]*|числ(?:о|а|у|ом|е|ами|ах)?|функци(?:я|и|ю|ей|ям|ями|ях)?|сил(?:а|ы|у|ой|е|ами|ах)?|величин(?:а|ы|у|ой|е|ами|ах)?|основани(?:е|я|ю|ем|и|ям|ями|ях)?|состояни(?:е|я|ю|ем|и|ях)?|зако(?:н|на|ну|ном|не|ны|нов|нами|нах)?)$/iu.test(genericTopic)) return "";
  // Exact catalog labels carry an authoritative subject; only free-form requests
  // should fall through to phrase aliases that can overlap across subjects.
  const canonical = matchCanonicalCurriculumTopic(topic);
  if (canonical) return canonical;
  for (const [subject, pattern] of specificSubjectAliases) if (pattern.test(topic)) return subject;
  if (/клетк[а-яё]*/i.test(topic) && !/(?:строени|делени|митоз|мейоз|мембран|ядр|цитоплазм|хромосом|организм|растени|бактери|биолог|раскраск|шахматн)/i.test(topic)) return "";
  for (const [subject, pattern] of Object.entries(subjectAliases)) if (pattern.test(topic)) return subject;
  return classifyCurriculumSubject(topic);
}

