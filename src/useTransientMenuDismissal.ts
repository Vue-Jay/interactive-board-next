import {useEffect,useLayoutEffect,useRef} from "react";

type Menu = {roots: readonly (Element|null)[]; close:()=>void};

/** Include portal children through an explicit link to their real trigger.
 * This keeps a parent popover open while its nested palette is being used. */
export function pointerInsideMenu(event: Event, roots: readonly (Element|null)[]): boolean {
 const target=event.target;
 if(!(target instanceof Node))return false;
 const path=event.composedPath();
 let node:Node|null=target;
 const seen=new Set<Node>();
 while(node&&!seen.has(node)){
  seen.add(node);
  if(roots.some(root=>root&&(root.contains(node)||path.includes(root))))return true;
  const element=node instanceof Element?node:node.parentElement;
  const owner=element?.closest<HTMLElement>("[data-menu-owner]")?.dataset.menuOwner;
  node=owner?document.getElementById(owner):null;
 }
 return false;
}

export function menuRoots(...selectors:string[]):Element[]{
 return selectors.flatMap(selector=>Array.from(document.querySelectorAll(selector)));
}

/** Capture before canvas/tool handlers that stop propagation. Never consume the
 * pointer: the outside control still receives its original action. Only
 * explicitly marked details are transient; ordinary disclosure sections stay. */
export function installTransientMenuDismissal(getMenus:()=>readonly Menu[],nativeDetails=false){
 const dismiss=(event:Event)=>{
  if(event.type==="pointerdown"&&(event as PointerEvent).isPrimary===false)return;
  // Native clicks generated by keyboards/assistive technology have no down event.
  if(event.type==="click"&&(event as MouseEvent).detail!==0)return;
  for(const menu of getMenus()){
   if(!pointerInsideMenu(event,menu.roots))menu.close();
  }
  if(nativeDetails)for(const details of document.querySelectorAll<HTMLDetailsElement>("details[data-dismiss-outside][open]")){
   if(!pointerInsideMenu(event,[details]))details.open=false;
  }
 };
 document.addEventListener("pointerdown",dismiss,true);
 document.addEventListener("click",dismiss,true);
 return ()=>{
  document.removeEventListener("pointerdown",dismiss,true);
  document.removeEventListener("click",dismiss,true);
 };
}

export function useTransientMenuDismissal(getMenus:()=>readonly Menu[],nativeDetails=false){
 const latest=useRef(getMenus);
 useLayoutEffect(()=>{latest.current=getMenus;});
 useEffect(()=>installTransientMenuDismissal(()=>latest.current(),nativeDetails),[nativeDetails]);
}
