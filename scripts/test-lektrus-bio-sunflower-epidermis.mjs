import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const cache=new Map();
function load(file){
 if(cache.has(file))return cache.get(file);
 const js=ts.transpileModule(readFileSync(file,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 const exp={};cache.set(file,exp);
 new Function("exports","require",js)(exp,dep=>load("src/"+dep.replace("./","")+".ts"));
 return exp;
}
const bio=load("src/lektrusBioMicroscopeModel.ts");
const zoom=load("src/lektrusBioUnifiedZoomModel.ts");
const nodes=bio.bioNodes("sunflower");
const named=(name)=>nodes.find(n=>n.name===name);
const plant=nodes[0],shoot=named("Побег"),leaf=named("Лист"),epidermis=named("Эпидермис листа"),guard=named("Замыкающая клетка устьица");
assert.ok(plant&&shoot&&leaf&&epidermis&&guard);
const chain=zoom.bioZoomPath(nodes,guard.id);
assert.deepEqual(chain.map(x=>x.level),bio.BIO_LEVELS);
assert.deepEqual(chain.map(x=>x.name),[plant.name,"Побег","Лист","Эпидермис листа","Замыкающая клетка устьица"]);
const preserved=nodes.find(n=>n.name==="Столбчатая паренхима");
assert.ok(preserved,"Old mesophyll tissue must remain present");
assert.ok(bio.bioChildren(nodes,leaf.id).some(n=>n.id===preserved.id),"Existing mesophyll branch must be retained");
const first=bio.withBioOrganism(bio.newBioMicroscope(),"sunflower");
assert.ok(bio.validBioMicroscope(first),"Existing saved paths must still validate");
assert.ok(bio.validBioMicroscope({...first,assignmentPath:chain.map(n=>n.id)}),"New assignment path must persist");
const images=chain.map(n=>zoom.bioZoomImageFor("sunflower",n));
assert.equal(images.length,5);
assert.ok(images.every(Boolean),"Every depth must now have species-specific visual evidence");
assert.equal(new Set(images.map(x=>x.file)).size,4,"The tissue and guard cell must reuse one real microscope frame");
assert.equal(images[3].file,images[4].file);
assert.equal(images[3].source,images[4].source);
assert.ok(zoom.bioZoomSharedFrame("sunflower",epidermis,guard));
assert.ok(zoom.bioZoomSharedFrame("sunflower",guard,epidermis));
assert.ok(!zoom.bioZoomSharedFrame("sunflower",leaf,epidermis),"Macro leaf and micrograph are physically different specimens");
for(const img of images){
 assert.match(img.file,/^https:\/\/commons.wikimedia.org\/wiki\/Special:FilePath\//);
 assert.match(img.source,/^https:\/\/commons.wikimedia.org\/wiki\/File:/);
 assert.match(img.license,/^CC BY/);
 assert.ok(img.author.length>4&&img.caption.length>28);
 assert.ok(!img.caption.includes("мезофилл"));
}
assert.equal(images[3].author,"ChrisInMilton");
assert.match(images[3].caption,/устьицами/);
assert.match(images[3].caption,/световая микроскопия/);
assert.equal(images[3].mode,"micrograph");
assert.equal(images[2].mode,"photograph");
assert.equal(zoom.bioZoomImageFor("sunflower",preserved),null,"Guard cell micrograph must not be reused as mesophyll");
const rootPoints=bio.bioChildren(nodes,plant.id);
assert.ok(rootPoints.length>=3);
const leafTissues=bio.bioChildren(nodes,leaf.id);
assert.equal(leafTissues.length,2);
const pts=leafTissues.map((n,i)=>zoom.bioZoomPoint("sunflower",leaf,n,i,2));
assert.ok(Math.hypot(pts[0].x-pts[1].x,pts[0].y-pts[1].y)>85,"Leaf tissue hotspots must not overlap");
for(let i=0;i<leafTissues.length;i++)
 assert.equal(zoom.bioZoomClosestChild("sunflower",leaf,leafTissues,pts[i],5)?.child.id,leafTissues[i].id);
const features=bio.bioCellFeatures(guard);
assert.equal(features.length,3);
for(const f of features)assert.ok(f.description.length>=65);
assert.ok(features.some(f=>f.name==="Устьичная щель"));
assert.ok(features.some(f=>f.name==="Замыкающие клетки"));
assert.ok(features.some(f=>f.name==="Клеточные стенки"));
const stage=readFileSync("src/LektrusBioUnifiedZoom.tsx","utf8");
assert.match(stage,/bioZoomSharedFrame\(organism,old,target\)/,"Same microphoto must not fade or jump");
assert.match(stage,/if\(target.parentId!==old.id\)setCam\(visits.current.get\(target.id\)\?\?BIO_ZOOM_INITIAL\)/);
assert.match(stage,/data-bio-zoom-target=\{child.id\}/);
assert.match(stage,/setCam\(zoomed\)/);
assert.match(stage,/bioZoomPan\(cameraRef.current/);
assert.match(stage,/onPointerMove=\{onMove\}/);
assert.match(stage,/map.size>=2/);
assert.match(stage,/setFocus\(Number\(e.target.value\)\)/);
console.log("Biology photo integration: Helianthus 5 true anatomical depths, 4 reviewed sources, real same-frame continuous microscopic zoom, 3 science-tested guard cell features, preserved mesophyll assignments and exact spatial spots.");
