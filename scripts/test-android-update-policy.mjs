import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {androidUpdateKind,compareAndroidVersions,parseAndroidUpdate,shouldOfferAndroidUpdate} from "../src/androidUpdatePolicy.ts";
const update={version:"1.0.4670",minimum_version:"1.0.4668",download_url:"https://github.com/Vue-Jay/interactive-board-next/releases/download/android-v1.0.4670/Lektrus-Android.apk",size_bytes:14685710};
assert.deepEqual(parseAndroidUpdate(update),update);
assert.deepEqual(parseAndroidUpdate({...update,catalog_stale:true}),{...update,catalog_stale:true});
assert.equal(compareAndroidVersions("1.0.99","1.0.100"),-1);
assert.equal(compareAndroidVersions("1.0.4669","1.0.4669"),0);
assert.equal(androidUpdateKind("1.0.4667",update),"required");
assert.equal(androidUpdateKind("1.0.4668",update),"optional");
assert.equal(androidUpdateKind("1.0.4670",update),"none");
assert.equal(androidUpdateKind("1.0.4671",update),"none");
assert.equal(androidUpdateKind("1.0",update),"none");
assert.equal(shouldOfferAndroidUpdate("1.0.4669",update,"1.0.4670",1000,999),false);
assert.equal(shouldOfferAndroidUpdate("1.0.4669",update,"1.0.4670",1000,1000),true);
assert.equal(shouldOfferAndroidUpdate("1.0.4669",update,"1.0.4670",1000,999,true),true);
assert.equal(shouldOfferAndroidUpdate("1.0.4667",update,"1.0.4670",1000,999),true);
assert.equal(parseAndroidUpdate({...update,minimum_version:"1.0.4671"}),null);
assert.equal(parseAndroidUpdate({...update,download_url:"https://example.org/unsafe.apk"}),null);
assert.equal(parseAndroidUpdate({...update,size_bytes:0}),null);
const gate=readFileSync(new URL("../src/AndroidUpdateGate.tsx",import.meta.url),"utf8");
assert.match(gate,/!required&&<button[^>]*className="lektrus-update-later"/);
assert.match(gate,/!blocking\|\|!visible\?children:null/);
assert.match(gate,/safeScreen\(\)\|\|initial&&kind==="required"/);
const profile=readFileSync(new URL("../src/ProfileScreen.tsx",import.meta.url),"utf8");
assert.doesNotMatch(profile,/<span>01<\/span>/);
console.log("Android update policy: optional, mandatory, postponed, newer installed, malformed metadata, trusted download, profile heading OK.");
