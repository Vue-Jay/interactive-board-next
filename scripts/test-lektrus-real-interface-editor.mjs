import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=(file)=>readFileSync(new URL("../"+file,import.meta.url),"utf8");
const app=read("src/App.tsx");
const admin=read("src/AdminScreen.tsx");
const editor=read("src/LektrusInterfaceStudio.tsx");
const css=read("src/lektrusInterfaceLayout.css");
const layout=read("src/lektrusInterfaceLayout.ts");
assert.match(admin,/onOpenLayout/,"admin should open the layout mode on a real board");
assert.match(app,/navigate\(`\/board\/\$\{own\.id\}\?layout-editor=1`\)/);
assert.match(app,/layoutEditing&&new URLSearchParams/,"preview must not recursively mount another editor");
assert.match(app,/get\("layout-preview"\)!=="1"/);
assert.match(app,/if \(!canEdit \|\| layoutEditing\) return;/,"no content write from interface editor");
assert.match(app,/if \(!editingLayout && pendingRaw/,"no template initialization");
assert.match(app,/if \(!editingLayout && raw && board\.role/,"no board upload in editor");
assert.doesNotMatch(editor,/li-stage-board|li-board-example|li-studio-inspector|<svg/i,
 "never create a fake board or icon set");
assert.match(editor,/querySelectorAll<HTMLElement>/,"find real BoardApp components");
assert.match(editor,/createPortal/,"use a true full-screen editing overlay");
assert.match(editor,/onPointerDown=\{pointerDown\}/);
assert.match(editor,/onPointerMove=\{pointerMove\}/);
assert.match(editor,/mode:"marquee"/);
assert.match(editor,/rectFromPoints/);
assert.match(editor,/intersects\(area,c\.box\)/);
assert.match(editor,/for\(const target of current\.targets\)/,"drag all selected targets together");
assert.match(editor,/past\.current\.pop\(\)/);
assert.match(editor,/future\.current\.pop\(\)/);
assert.match(editor,/onClick=\{undo\}/);
assert.match(editor,/onClick=\{redo\}/);
assert.match(editor,/>↶ Отменить<\/button>/);
assert.match(editor,/>↷ Вернуть<\/button>/);
assert.match(editor,/deviceProfiles\.map/,"switch between all four presets");
assert.match(editor,/className="lektrus-layout-device-frame"/,"responsive preview runs real board at target width");
assert.match(editor,/layout-editor=1&layout-preview=1/);
assert.match(layout,/desktop.*laptop.*tablet.*phone/,"device variants persist independently");
assert.match(css,/\.lektrus-live-layout-marquee/);
assert.match(css,/\.lektrus-layout-device-frame/);
console.log("Lektrus layout editor: full-screen real board, undo/redo, marquee selection, group moves, desktop preview of four device resolutions.");
